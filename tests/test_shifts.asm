-- test_shifts.asm
-- Tests: SHL, SHR, SAR, ROL, ROR with various shift amounts
--
-- Shift amount is a 4-bit immediate (0-15) encoded in instruction.
-- Syntax: SHL $rd, $N shifts Rd left by N positions.
--
-- Memory map for test results:
--   addr 0: SHL by 1 (expected: 0x000E = 7 << 1 = 14)
--   addr 1: SHL by 4 (expected: 0x0070 = 7 << 4 = 112)
--   addr 2: SHR by 1 (expected: 0x0003 = 7 >> 1 = 3)
--   addr 3: SHR by 4 (expected: 0x0010 = 0x100 >> 4 = 16)
--   addr 4: SAR positive (expected: 0x0010 = 0x100 >> 4 arithmetic)
--   addr 5: SAR negative (expected: 0xFFF0 = 0xFF00 >> 4 arithmetic)
--   addr 6: ROL by 1 (expected: 0x0001 = 0x8000 rotated left 1)
--   addr 7: ROR by 1 (expected: 0x8000 = 0x0001 rotated right 1)
--   addr 8: SHL by 0 (expected: 0x0007, unchanged)
--   addr 9: ROL by 4 (expected: 0x0050 = 0x0005 rotated left 4)

-- Setup test values
LIL $1, 7           -- $1 = 7
LIW $2, 0x0100      -- $2 = 0x100 (256)
LIW $3, 0xFF00      -- $3 = 0xFF00 (-256 signed)
LIW $4, 0x8000      -- $4 = 0x8000 (MSB set)
LIL $5, 5           -- $5 = 5
LIL $13, 1          -- $13 = 1
NOP
NOP
NOP

-- ============================================================
-- Test 1: SHL by 1 — 7 << 1 = 14
-- ============================================================
AND $6, $0
NOP
OR $6, $1
NOP
SHL $6, $1           -- $6 = 7 << 1 = 14 = 0x000E
NOP
SW $6, 0($0)

-- ============================================================
-- Test 2: SHL by 4 — 7 << 4 = 112
-- ============================================================
AND $6, $0
NOP
OR $6, $1
NOP
SHL $6, $4           -- $6 = 7 << 4 = 112 = 0x0070
NOP
SW $6, 1($0)

-- ============================================================
-- Test 3: SHR by 1 — 7 >> 1 = 3
-- ============================================================
AND $6, $0
NOP
OR $6, $1
NOP
SHR $6, $1           -- $6 = 7 >> 1 = 3 = 0x0003
NOP
SW $6, 2($0)

-- ============================================================
-- Test 4: SHR by 4 — 0x100 >> 4 = 0x10
-- ============================================================
AND $6, $0
NOP
OR $6, $2
NOP
SHR $6, $4           -- $6 = 0x100 >> 4 = 0x010 = 16
NOP
SW $6, 3($0)

-- ============================================================
-- Test 5: SAR positive — 0x100 >> 4 arithmetic (sign bit 0)
-- ============================================================
AND $6, $0
NOP
OR $6, $2
NOP
SAR $6, $4           -- $6 = 0x100 >>> 4 = 0x0010
NOP
SW $6, 4($0)

-- ============================================================
-- Test 6: SAR negative — 0xFF00 >> 4 arithmetic (sign bit 1)
-- 0xFF00 = 1111_1111_0000_0000
-- >> 4  = 1111_1111_1111_0000 = 0xFFF0
-- ============================================================
AND $6, $0
NOP
OR $6, $3
NOP
SAR $6, $4           -- $6 = 0xFF00 >>> 4 = 0xFFF0
NOP
SW $6, 5($0)

-- ============================================================
-- Test 7: ROL by 1 — rotate 0x8000 left by 1
-- 0x8000 ROL 1 = 0x0001
-- ============================================================
AND $6, $0
NOP
OR $6, $4
NOP
ROL $6, $1           -- $6 = 0x0001
NOP
SW $6, 6($0)

-- ============================================================
-- Test 8: ROR by 1 — rotate 0x0001 right by 1
-- 0x0001 ROR 1 = 0x8000
-- ============================================================
AND $6, $0
NOP
OR $6, $13
NOP
ROR $6, $1           -- $6 = 0x8000
NOP
SW $6, 7($0)

-- ============================================================
-- Test 9: SHL by 0 — should not change value
-- ============================================================
AND $6, $0
NOP
OR $6, $1
NOP
SHL $6, $0           -- $6 = 7 << 0 = 7
NOP
SW $6, 8($0)

-- ============================================================
-- Test 10: ROL by 4 — rotate 0x0005 left by 4
-- 0x0005 = 0000_0000_0000_0101
-- ROL 4 = 0000_0000_0101_0000 = 0x0050
-- ============================================================
AND $6, $0
NOP
OR $6, $5
NOP
ROL $6, $4           -- $6 = 0x0050
NOP
SW $6, 9($0)

-- End
HALT: J %HALT%
NOP
